"""Assembles the data bundle that the knowledge build's producers read, from this repository and one public download.

    python tools/make_bundle.py --out ../build/bundle [--wsm <path to WSM_Database_2025.csv>] [--no-kit]
    python -m producers --bundle ../build/bundle --out ../build/landing

It writes, under the bundle:
  processed/geospatial/basins-pack.json, processed/application/*.json  the app's packs (app/src/data), copied
  processed/wells/*.json, processed/seismic/seismic-figures.json       the well and seismic extractions, from the packs
  processed/geology/fabric-iq-kit/, processed/geology/ontology/       the curated knowledge-graph kit, generated by the
                                                                      app's own graph code (tools/export-kits.ts)
  source/geospatial/world-stress-map-2025/WSM_Database_2025.csv       the World Stress Map, when --wsm names a download

The packs carry only sources whose reuse terms allow redistribution, so everything generated from them does too. The kit
needs Node and the app's packages (cd app && npm ci); --no-kit leaves it out. The World Stress Map is published by GFZ
under CC BY 4.0 and is downloaded by hand from https://doi.org/10.5880/WSM.2025.001. ingestion-framework/docs/
KNOWLEDGE_INPUTS.md describes every input, the optional library manifest and the counts to expect. Existing files in the
bundle that this script doesn't write are left as they are.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "app" / "src" / "data"
WSM = Path("source/geospatial/world-stress-map-2025/WSM_Database_2025.csv")
WSM_TESTED_SHA256 = "3b24aa5b33b251b6c52ee25bcafe3d23d036deb1c38e1caae51f63b808605d1b"
WSM_COLUMNS = {"ID", "LAT", "LON", "AZI", "TYPE", "DEPTH", "QUALITY", "REGIME", "COUNTRY"}
IMAGE_KEYS = {"img", "b64", "thumb", "image", "src", "extraImages"}


def strip(value):
    """The record without embedded images, which the knowledge build doesn't read."""
    if isinstance(value, dict):
        return {k: strip(v) for k, v in value.items() if k not in IMAGE_KEYS and not (isinstance(v, str) and v.startswith("data:"))}
    if isinstance(value, list):
        return [strip(v) for v in value]
    return value


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def copy_packs(out: Path) -> None:
    copies = {
        DATA / "basins-pack.json": out / "processed" / "geospatial" / "basins-pack.json",
        DATA / "app-pack.json": out / "processed" / "application" / "app-pack.json",
        DATA / "lowcarbon-pack.json": out / "processed" / "application" / "lowcarbon-pack.json",
    }
    for src, dst in copies.items():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        print(f"{dst.relative_to(out)}  <-  {src.relative_to(ROOT)}")


def write_extractions(out: Path) -> None:
    app = json.loads((DATA / "app-pack.json").read_text(encoding="utf-8"))
    low = json.loads((DATA / "lowcarbon-pack.json").read_text(encoding="utf-8"))
    files = {
        out / "processed" / "wells" / "wells.json": app["wells"],
        out / "processed" / "wells" / "velocity.json": app["velocity"],
        out / "processed" / "wells" / "lowcarbon-sites.json": low["sites"],
        out / "processed" / "seismic" / "seismic-figures.json": app["figures"],
    }
    for path, value in files.items():
        write_json(path, strip(value))
        print(f"{path.relative_to(out)}  <-  the app's packs")


def write_kit(out: Path) -> None:
    if not (ROOT / "app" / "node_modules").is_dir():
        sys.exit("The knowledge-graph kit is generated by the app's graph code. Run `npm ci` in app/ first, or pass --no-kit.")
    target = out / "processed" / "geology"
    subprocess.run(["node", str(ROOT / "tools" / "run-ts.mjs"), str(ROOT / "tools" / "export-kits.ts"), str(target)], check=True, cwd=ROOT)
    print(f"{target.relative_to(out)}/fabric-iq-kit and ontology  <-  tools/export-kits.ts")


def add_wsm(out: Path, source: Path) -> None:
    with source.open(encoding="utf-8-sig", newline="") as fh:
        header = set(next(csv.reader(fh), []))
    if not WSM_COLUMNS <= header:
        sys.exit(f"{source} doesn't look like the World Stress Map database: missing columns {sorted(WSM_COLUMNS - header)}")
    target = out / WSM
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    note = "" if digest == WSM_TESTED_SHA256 else " (differs from the tested release file, so stress counts may differ slightly)"
    print(f"{WSM}  <-  {source}, SHA-256 {digest}{note}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True, help="bundle folder to create or refresh")
    ap.add_argument("--wsm", type=Path, help="the downloaded WSM_Database_2025.csv")
    ap.add_argument("--no-kit", action="store_true", help="don't generate the knowledge-graph kit (needs Node and the app's packages)")
    args = ap.parse_args()
    out = args.out.resolve()
    copy_packs(out)
    write_extractions(out)
    if not args.no_kit:
        write_kit(out)
    if args.wsm:
        add_wsm(out, args.wsm.resolve())
    elif not (out / WSM).is_file():
        print(f"No World Stress Map yet: download it from https://doi.org/10.5880/WSM.2025.001 and pass --wsm, or the stress records are left out.")
    print(f"Bundle ready at {out}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
